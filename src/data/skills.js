/** Flattened id -> skill lookup, built once at module load. */
export const SKILLS_BY_ID = Object.fromEntries(
  Object.values(SKILLS_BY_CLASS)
    .flat()
    .map((skill) => [skill.id, skill]),
)

/** Skill list for one class, in Q/E/R/F/C order. */
export function skillsForClass(classId) {
  return SKILLS_BY_CLASS[classId] ?? SKILLS_BY_CLASS.vanguard
}
